/**
 * convert_finish_int.mjs
 *
 * Reads the FInish_Int sheet from NEW_DATA_OAKSOME - Copy.xlsx and generates
 * finish_int_items.js using the Option-C composite-key structure.
 *
 * Each FINISH_INT item stores one string per valid combination:
 *   "COLLECTION 1§FA_01_MEL§0WE28_CST"
 *
 * At load time the app converts the combos array to a Set for O(1) lookup.
 *
 * Run:
 *   node src/data/convert_finish_int.mjs
 */

import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'
import xlsx from 'xlsx'

const __dir  = dirname(fileURLToPath(import.meta.url))
const xlsxPath = join(__dir, 'NEW_DATA_OAKSOME - Copy.xlsx')
const outPath  = join(__dir, 'finish_int_items.js')

// ── Read sheet ────────────────────────────────────────────────────────────────

const workbook  = xlsx.readFile(xlsxPath)
const worksheet = workbook.Sheets['FInish_Int']

if (!worksheet) {
  console.error('Sheet "FInish_Int" not found. Available sheets:', workbook.SheetNames)
  process.exit(1)
}

// header_row: 0 = false  →  returns a 2-D array; row 0 & 1 are the two header rows
const rawRows = xlsx.utils.sheet_to_json(worksheet, { header: 1, defval: '' })

// Data starts at row index 2 (rows 0 and 1 are headers)
const dataRows = rawRows.slice(2)

console.log(`Total data rows: ${dataRows.length}`)

// ── Column indices (0-based) ───────────────────────────────────────────────────
const COL_VALUE       = 0   // FINISH_INT item key
const COL_LABEL       = 1   // FINISH_INT display name
const COL_COLLECTION  = 2   // Filter key 1 — collection
const COL_FINISH_EXT  = 7   // Filter key 3 — Decor_Texture (FINISH_EXT value key)
const COL_FRONT       = 12  // Filter key 2 — Colonne6 (exact FRONT_TYPE value)
const COL_IMG_INT     = 24  // Lien_IMG_Int — interior finish image path

// ── Aggregate ─────────────────────────────────────────────────────────────────

/** @type {Map<string, { value: string; label: string; Lien_IMG_Int: string; combos: Set<string> }>} */
const itemMap = new Map()

let skipped = 0

for (const row of dataRows) {
  const value      = String(row[COL_VALUE]      ?? '').trim()
  const label      = String(row[COL_LABEL]      ?? '').trim()
  const collection = String(row[COL_COLLECTION] ?? '').trim()
  const front      = String(row[COL_FRONT]      ?? '').trim()
  const finishExt  = String(row[COL_FINISH_EXT] ?? '').trim()
  const imgInt     = String(row[COL_IMG_INT]    ?? '').trim()

  if (!value || !collection || !front || !finishExt) {
    skipped++
    continue
  }

  if (!itemMap.has(value)) {
    itemMap.set(value, { value, label, Lien_IMG_Int: imgInt, combos: new Set() })
  }

  itemMap.get(value).combos.add(`${collection}§${front}§${finishExt}`)
}

console.log(`Skipped rows (missing key field): ${skipped}`)
console.log(`Unique FINISH_INT items: ${itemMap.size}`)

// ── Serialise ─────────────────────────────────────────────────────────────────

const items = [...itemMap.values()].map(({ value, label, Lien_IMG_Int, combos }) => ({
  value,
  label,
  Lien_IMG_Int,
  combos: [...combos].sort(),
}))

// Log combo counts for verification
for (const item of items) {
  console.log(`  ${item.value.padEnd(16)} "${item.label.padEnd(24)}"  combos: ${item.combos.length}`)
}

const js = `// AUTO-GENERATED — do not edit by hand.
// Source: NEW_DATA_OAKSOME - Copy.xlsx  (sheet: FInish_Int)
// Generated by: src/data/convert_finish_int.mjs
//
// Each item stores one composite string per valid (collection × front × finish_ext) triplet.
// The app must convert .combos → .comboSet (Set) at load time for O(1) filtering.

const FINISH_INT_ITEMS = ${JSON.stringify(items, null, 2)};

export default FINISH_INT_ITEMS;
`

writeFileSync(outPath, js, 'utf8')
console.log(`\nWrote ${items.length} items to ${outPath}`)
